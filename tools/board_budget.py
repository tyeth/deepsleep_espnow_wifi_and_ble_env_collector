"""
board_budget.py - will this tree even import on that board, and roughly how
much heap will it take? No hardware, no CircuitPython: CPython's `ast`
plus mpy-cross.

    python tools/board_budget.py collector/hub_main.py node/node_lite.py node/node_full.py
    python tools/board_budget.py --board-toml path/to/circuitpython.toml node/node_lite.py
    MPY_CROSS=~/circuitpython/mpy-cross/build/mpy-cross python tools/board_budget.py ...

For each entry module it walks the import graph inside its tree and reports
every import of a CircuitPython built-in that the board does not have,
split into

  HARD   an unconditional module-level `import x` on the path from the
         entry: the module raises ImportError at load, nothing after it runs
  soft   inside a try/except that catches ImportError, under an `if`, or
         inside a function: the feature degrades or is skipped

Local modules reached only through such imports inherit that status. Third-party libraries (anything not local and not built-in) are
listed so you can check them against requirements-circup.txt.

The default board table is the one both Raspberry Pi Pico W zephyr-cp boards
generate (raspberrypi/rpi_pico_w_zephyr and rpi_pico2_w_zephyr,
tyeth/circuitpython @ 94bfd47b5f -- identical module lists). Pass
--board-toml with a board's autogenerated circuitpython.toml for any other.

Heap estimate: with mpy-cross available (MPY_CROSS or the usual build
paths) every reachable local .py is compiled and the .mpy sizes summed.
Measured on this project's modules, a loaded module holds about 1.2x its
.mpy size on a 32-bit build (2.0x on the 64-bit unix port), so the estimate
is sum(.mpy) x 1.2 for the local tree, plus the staged lib/*.mpy the entry
pulls in if a lib/ directory exists. It says nothing about runtime buffers
(sockets, TLS, display bitmaps) -- treat it as the floor.
"""

